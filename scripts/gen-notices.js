'use strict';

// 汇总打进插件包的第三方库许可证，输出 THIRD_PARTY_NOTICES.md。
// 任何库的许可证不在白名单内时报错，防止带入 GPL/LGPL 等限制性协议。

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const ALLOWED = new Set(['MIT', '0BSD']);

// 用途说明中英双语，与 README 保持一致。
// parent 为 null 表示 package.json 里的直接依赖；否则是该库的依赖方，用来沿依赖链解析安装位置
// （pnpm 的 node_modules 顶层只有直接依赖，间接依赖在 .pnpm 虚拟仓库里）。
const BUNDLED = [
  { name: '@sabaki/sgf', parent: null, role: 'SGF parsing / SGF 解析' },
  {
    name: '@sabaki/go-board',
    parent: null,
    role: 'Board rules: moves, captures, liberties / 棋盘规则（落子、提子、气）',
  },
  {
    name: '@sabaki/influence',
    parent: null,
    role: 'Position estimate: territory ownership / 形势估算（领地归属）',
  },
  {
    name: 'doken',
    parent: '@sabaki/sgf',
    role: 'Tokenizer dependency of @sabaki/sgf / @sabaki/sgf 的词法分析依赖',
  },
  {
    name: 'iconv-lite',
    parent: '@sabaki/sgf',
    role: 'Encoding conversion dependency of @sabaki/sgf / @sabaki/sgf 的字符编码转换依赖',
  },
  {
    name: 'safer-buffer',
    parent: 'iconv-lite',
    role: 'Dependency of iconv-lite / iconv-lite 的依赖',
  },
  {
    name: 'jschardet',
    parent: '@sabaki/sgf',
    role: 'Encoding detection dependency of @sabaki/sgf / @sabaki/sgf 的字符编码探测依赖',
  },
];

const installDirs = new Map();

function findUpward(start, name) {
  for (let dir = start; ; dir = path.dirname(dir)) {
    const candidate = path.join(dir, 'node_modules', name);
    if (fs.existsSync(path.join(candidate, 'package.json'))) return candidate;
    if (path.dirname(dir) === dir) return path.join(start, 'node_modules', name);
  }
}

/**
 * 找到库在磁盘上的实际目录。直接依赖在项目 node_modules 下，间接依赖从依赖方的真实路径向上查找，
 * 对 npm 的扁平布局和 pnpm 的符号链接布局都适用。
 */
function installDir({ name, parent }) {
  if (installDirs.has(name)) return installDirs.get(name);
  let dir;
  if (parent === null) {
    dir = path.join(root, 'node_modules', name);
  } else {
    const parentEntry = BUNDLED.find((b) => b.name === parent);
    // realpath 跟随符号链接，得到依赖方真正所在的目录，再沿父目录逐级找 node_modules/<name>。
    // 不用 require.resolve：部分包的 exports 没有放行 package.json，解析会失败。
    dir = findUpward(fs.realpathSync(installDir(parentEntry)), name);
  }
  if (!fs.existsSync(path.join(dir, 'package.json'))) {
    throw new Error(
      `${name} is not installed, run the package manager's install first / ${name} 未安装，请先安装依赖`,
    );
  }
  installDirs.set(name, dir);
  return dir;
}

function repoUrl(pkg) {
  const url = (pkg.repository && (pkg.repository.url || pkg.repository)) || pkg.homepage || '';
  return String(url)
    .replace(/^git\+/, '')
    .replace(/\.git$/, '');
}

function readLicenseText(dir) {
  const file = fs.readdirSync(dir).find((f) => /^licen[sc]e(\.|$)/i.test(f));
  if (!file) throw new Error(`No LICENSE file found in ${dir} / ${dir} 下找不到 LICENSE 文件`);
  return fs.readFileSync(path.join(dir, file), 'utf8').trim();
}

const sections = BUNDLED.map((entry) => {
  const { name, role } = entry;
  const dir = installDir(entry);
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  if (!ALLOWED.has(pkg.license)) {
    const allowed = [...ALLOWED].join('/');
    throw new Error(
      `${name}@${pkg.version} is licensed under ${pkg.license}, which is not in the allowlist ${allowed} / ` +
        `${name}@${pkg.version} 的许可证是 ${pkg.license}，不在白名单 ${allowed} 内`,
    );
  }
  return [
    `## ${name} ${pkg.version}`,
    '',
    `- Purpose / 用途: ${role}`,
    `- License / 许可证: ${pkg.license}`,
    `- Project / 项目地址: ${repoUrl(pkg)}`,
    '',
    '```text',
    readLicenseText(dir),
    '```',
    '',
  ].join('\n');
});

const header = [
  '# Third-Party Notices / 第三方软件声明',
  '',
  'The published package of this extension contains code from the open-source libraries below. Their copyright and license notices follow.',
  'This file is generated by `scripts/gen-notices.js` from the actual files in node_modules.',
  '',
  '本插件的发布包中包含下列开源库的代码，其版权声明与许可声明如下。',
  '本文件由 `scripts/gen-notices.js` 根据 node_modules 中的实际文件生成。',
  '',
].join('\n');

fs.writeFileSync(
  path.join(root, 'THIRD_PARTY_NOTICES.md'),
  `${header}\n${sections.join('\n')}`,
  'utf8',
);
console.log(
  `Generated THIRD_PARTY_NOTICES.md (${BUNDLED.length} libraries) / 已生成 THIRD_PARTY_NOTICES.md（${BUNDLED.length} 个库）`,
);
